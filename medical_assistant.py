# ================== 零依赖、零报错、CPU友好的OCR方案 ==================
import easyocr
# 初始化CPU版OCR，仅加载中文模型
reader = easyocr.Reader(['ch_sim'], gpu=False)

def ocr_medical_image(img_path):
    """图片OCR识别：体检报告/心电图（EasyOCR版，零Paddle依赖）"""
    try:
        # 识别图片，detail=0直接返回纯文本列表
        result = reader.readtext(img_path, detail=0, paragraph=True)
        return "\n".join(result)
    except Exception as e:
        return f"图片识别失败：{str(e)}"

class MedicalAssistant:
    def __init__(self, checkpoint_path="./final_model"):
        self.checkpoint_path = "./final_model"
        self.device, self.dtype = self._select_device_and_dtype()
        self.model = None
        self.tokenizer = None
        self.conversation_history = []
        self.loaded_hospitals = {}

    def _select_device_and_dtype(self):
        if torch.cuda.is_available():
            try:
                major, _ = torch.cuda.get_device_capability()
                if major >= 12:
                    raise RuntimeError("Unsupported CUDA capability")
                _ = torch.zeros(1, device="cuda")
                return "cuda", torch.float16
            except Exception:
                pass
        return "cpu", torch.float32

    def load_model(self):
        print("正在加载医疗助手模型...")
        if not os.path.exists(self.checkpoint_path):
            raise FileNotFoundError(f"模型路径不存在: {self.checkpoint_path}")

        self.tokenizer = AutoTokenizer.from_pretrained(
            self.checkpoint_path, use_fast=False, trust_remote_code=True, local_files_only=True
        )
        if self.tokenizer.pad_token is None and self.tokenizer.eos_token is not None:
            self.tokenizer.pad_token = self.tokenizer.eos_token

        self.model = AutoModelForCausalLM.from_pretrained(
            self.checkpoint_path, torch_dtype=self.dtype, local_files_only=True
        )
        self.model.to(self.device)
        self.model.eval()
        print(f"模型加载完成！使用设备: {self.device}")

    def predict(self, messages, max_new_tokens=512):
        model_device = next(self.model.parameters()).device
        text = self.tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True
        )
        inputs = self.tokenizer([text], return_tensors="pt")
        input_ids = inputs.input_ids.to(model_device)
        attention_mask = inputs.attention_mask.to(model_device) if hasattr(inputs, "attention_mask") else None

        generated = self.model.generate(
            input_ids=input_ids, attention_mask=attention_mask, max_new_tokens=max_new_tokens
        )
        new_tokens = generated[:, input_ids.shape[1]:]
        response = self.tokenizer.batch_decode(new_tokens, skip_special_tokens=True)[0]
        return response

